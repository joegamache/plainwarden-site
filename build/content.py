# ---------- Articles (one file per article in build/articles/<slug>.html) ----------
import json as _json, glob as _glob
A = []
for _p in sorted(_glob.glob(os.path.join(HERE, 'articles', '*.html'))):
    _raw = open(_p).read()
    _m = re.match(r'<!--META\n(.*?)\nMETA-->\n', _raw, re.S)
    _meta = _json.loads(_m.group(1))
    A.append((os.path.basename(_p)[:-5], _meta['title'], _meta['description'], _raw[_m.end():], _meta.get('references', []), _meta))
A.sort(key=lambda a: a[5].get('published', ''))
os.makedirs(OUT + '/learn', exist_ok=True)
for slug, title, desc, body, refs, _meta in A:
    b = (f'<p class="crumb"><a href="index.html">Learn</a></p><h1>{_h.escape(title)}</h1><p class="lead">{_h.escape(desc)}</p>' + body +
         f'<p class="refs"><b>References:</b> {_h.escape("; ".join(refs))}</p>')
    guide_page('__a.html', title, b, desc)
    s = open(OUT + '/guides/__a.html').read(); os.remove(OUT + '/guides/__a.html')
    s = s.replace('<a href="index.html">Guides</a>', '<a href="../guides/index.html">Guides</a><a href="index.html">Learn</a>')
    open(OUT + '/learn/' + slug + '.html', 'w').write(s)
idx = ('<h1>Learn</h1><p class="lead">Plain-English articles on written information security plans for tax and accounting practices.</p><div class="box"><ul>' +
       ''.join(f'<li><a href="{s}.html"><b>{_h.escape(t)}</b></a><br><span class="muted">{_h.escape(d)}</span></li>' for s, t, d, *_ in A) + '</ul></div>' +
       '<p>Looking for step-by-step fixes? See the <a href="../guides/index.html">how-to guides</a>.</p>')
guide_page('__a.html', 'Learn', idx, 'Articles on written information security plans for tax and accounting practices.')
s = open(OUT + '/guides/__a.html').read(); os.remove(OUT + '/guides/__a.html')
s = s.replace('<a href="index.html">Guides</a>', '<a href="../guides/index.html">Guides</a><a href="index.html">Learn</a>')
open(OUT + '/learn/index.html', 'w').write(s)
ARTICLE_SLUGS = [a[0] for a in A]
